#!/usr/bin/env node
// @ts-check
/// <reference types="node" />
// 构建 client.js：rolldown 把 src/client-entry.ts 打包为 CJS（react / zod 精确外置），再包进
// window.__ModuleLoader__.load({ id, factory }) UMD 外壳。id 取 package.json 的 name，
// 与 dsh.client 模块表键一致。
// 编排（外置判据、store 路径折叠、外壳拼装）统一住在 @jayyuen66/dsh-plugin-shared/
// lib/build-client；本文件只声明入口、生成头与本仓自有的包名同源校验。
// 运行：node build-client.mjs（或 npm run build:client）。buildClient() 供测试导入。
import path from "node:path";
import { rolldown } from "rolldown";
import {
  buildClientBundle,
  REACT_RUNTIME_MODULES,
} from "@jayyuen66/dsh-plugin-shared/lib/build-client";
import { invokedDirectly, writeArtifact } from "@jayyuen66/dsh-plugin-shared/lib/build-artifacts";

export { singleEntryChunk } from "@jayyuen66/dsh-plugin-shared/lib/build-artifacts";

const root = import.meta.dirname;

// 外置清单 = 既有 react 家族 + zod（宿主 `PLATFORM_MODULES` 里本卡值导入的第三方运行时）。
// 不复用 shared 的默认清单、也不 import 它的新导出：消费者 CI 装的是 registry 上那份 shared，
// 新导出在它发布之前不存在。zod 内联会打进每份 client.js，并让同一页面出现两份 zod 身份。
const CLIENT_EXTERNALS = [...REACT_RUNTIME_MODULES, "zod"];

/** 生成 client.js 的完整文本（含 ModuleLoader 外壳）。 */
export async function buildClient() {
  return buildClientBundle({
    root,
    rolldown,
    externals: CLIENT_EXTERNALS,
    header:
      "// GENERATED by buildClient() in build-client.mjs — edit src/client-entry.ts, then run `node build-client.mjs`.",
    verifyName: ({ pkgName, body }) => {
      // 槽位 key 写死在 src 的 BUNDLE_PKG，外壳 id 取自 package.json.name。宿主按包名逐字
      // 匹配模块表键，对不上就是整张卡静默不渲染，而改名在别的环节没有症状。
      // 所以判据必须读 BUNDLE_PKG 的声明值本身：产物里包名一共出现多次（外壳 id、BUNDLE_PKG 的
      // 声明与引用），拿 includes 去判会被其中任意一处满足，而这个不变量要的正是「这几处同源」。
      // 捕获组命名（lint 要求）但按位置取值：括号访问与点号访问两条规则互相打架，位置索引
      // 对两边都成立。
      const declared = /(?:const|let|var)\s+BUNDLE_PKG\s*=\s*(?<literal>"(?:[^"\\]|\\.)*")/u.exec(
        body,
      );
      const literal = declared?.[1];
      if (literal === undefined) {
        throw new Error(
          "build-client：产物里找不到 BUNDLE_PKG 的声明，src/client-entry.ts 的槽位 key 无从核对。",
        );
      }
      if (JSON.parse(literal) !== pkgName) {
        throw new Error(
          `build-client：src 的 BUNDLE_PKG 是 ${literal}，package.json 的 name 是 ${JSON.stringify(pkgName)}——两者不同源，槽位 key 与模块表键会对不上。`,
        );
      }
    },
  });
}

async function main() {
  const out = await buildClient();
  await writeArtifact(path.join(root, "client.js"), out);
  console.info("client.js written:", Buffer.byteLength(out, "utf8"), "bytes");
}

if (invokedDirectly(import.meta.filename)) {
  try {
    await main();
  } catch (error) {
    console.error(error);
    process.exitCode = 1;
  }
}
